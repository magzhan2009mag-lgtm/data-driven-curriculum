def how(method: str, n_students: int | None = None, n_results: int | None = None, tests: list[dict] | None = None) -> dict:
    return {"method": method, "n_students": n_students, "n_results": n_results, "tests": tests or []}


def check(label: str, p_value: float | None = None, effect_name: str | None = None,
          effect_size: float | None = None, effect_label: str | None = None) -> dict:
    """Одна проверка: что сравнивали, p-value с поправкой и размер эффекта."""
    return {"label": label, "p_value": p_value, "effect_name": effect_name, "effect_size": effect_size,
            "effect_label": effect_label}
